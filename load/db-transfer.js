// Logical export/import for a LOOM database.
//
// Used to move a development database between Supabase projects (e.g. when a
// project must be recreated in another region). Schema is NOT transferred here
// -- that is load/migrations/000_base_schema.sql + 001..N. Only rows move.
//
//   export  node --import ./load/env-local.js load/db-transfer.js export --out load/snapshots/x.json
//   import  node --import ./load/env-local.js load/db-transfer.js import --in  load/snapshots/x.json
//   verify  node --import ./load/env-local.js load/db-transfer.js verify --in  load/snapshots/x.json
//   diff    node --import ./load/env-local.js load/db-transfer.js diff   --a a.json --b b.json
//
// Row fidelity: every row is exported as `to_jsonb(row)`, so Postgres itself
// performs the type->JSON conversion (timestamptz, numeric, uuid, jsonb, text[],
// bytea all round-trip through their canonical input form). Import casts each
// JSON key back to the live column type via jsonb_to_recordset, so there is no
// per-value guessing.
//
// NOTE: the JSON is bound through `$1::text::jsonb`, not `$1::jsonb`. When the
// parameter type is inferred as jsonb directly, postgres-js sends the JS string
// as a quoted literal and Postgres parses `[...]` as a JSON *string* (scalar),
// which makes jsonb_to_recordset fail with "cannot call jsonb_to_recordset on
// a non-array". Going through text first makes Postgres parse the literal as
// JSON content instead.
//
// auth.users / auth.identities are copied too, preserving UUIDs and bcrypt
// `encrypted_password` hashes so existing logins survive the move.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postgres from "postgres";
import { databaseUrl, targetDatabaseUrl } from "./env-local.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Never move the migration ledger — the target tracks its own applied state.
const SKIP_TABLES = new Set(["public.schema_migrations"]);

// auth.users columns that are safe and meaningful to carry across projects.
// Everything else (flow state, one-time tokens, sessions, SSO) is per-project
// runtime state and must be regenerated by the target. Generated columns (e.g.
// Supabase's computed confirmed_at) are filtered out at runtime by introspecting
// attgenerated/attidentity against the target.
const AUTH_USER_COLS = [
  "id", "aud", "role", "email", "encrypted_password", "email_confirmed_at",
  "invited_at", "confirmation_token", "confirmation_sent_at",
  "email_change_token_new", "email_change", "email_change_sent_at",
  "last_sign_in_at", "raw_app_meta_data", "raw_user_meta_data",
  "is_super_admin", "created_at", "updated_at",
  "phone", "phone_confirmed_at", "recovery_token", "recovery_sent_at",
];
const AUTH_IDENTITY_COLS = [
  "id", "user_id", "identity_data", "provider", "provider_id",
  "last_sign_in_at", "created_at", "updated_at",
];

// GoTrue treats these as plain strings, not NULLs. A migrated row that carries
// NULL makes every password grant fail with
//   500 {"code":"unexpected_failure","message":"Database error querying schema"}
// (while an unknown email still returns 400, so it looks like a per-user fault).
// Native rows always store empty strings here, so normalise on import.
const NULLABLE_AS_EMPTY = [
  "confirmation_token", "recovery_token", "email_change_token_new",
  "email_change", "email_change_token_current", "phone_change_token",
  "phone_change", "reauthentication_token", "invited_at",
];

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
};
const mode = process.argv[2];

// One-off repair for databases already imported by an earlier version of this
// script. See repair-auth-instances and repair-auth-tokens below.
// Usage: node --import ./load/env-local.js load/db-transfer.js repair-auth
async function doRepairAuth() {
  const sql = connect();
  try {
    await doRepairAuthInstancesWith(sql);
    await doRepairAuthTokensWith(sql);
  } finally { await sql.end(); }
}

async function doRepairAuthInstancesWith(sql) {
  const [inst] = await sql.unsafe("SELECT id FROM auth.instances LIMIT 1");
  const target = inst ? inst.id : "00000000-0000-0000-0000-000000000000";
  const rows = await sql.unsafe(
    "UPDATE auth.users SET instance_id = $1::uuid WHERE instance_id IS NULL RETURNING id", [target]);
  console.log(`instance_id: repaired ${(rows || []).length || 0} auth.users rows -> ${target}`);
}

async function doRepairAuthTokensWith(sql) {
  const sets = NULLABLE_AS_EMPTY.filter((c) => c !== "invited_at")
    .map((c) => `${c} = ''`).join(", ");
  const rows = await sql.unsafe(
    `UPDATE auth.users SET ${sets} WHERE ${NULLABLE_AS_EMPTY.filter((c) => c !== "invited_at")
      .map((c) => `${c} IS NULL`).join(" OR ")} RETURNING id`);
  console.log(`tokens: NULL -> '' on ${(rows || []).length || 0} auth.users rows`);
  // Ensure every migrated user is marked email-verified, matching native rows.
  const r2 = await sql.unsafe(`
    UPDATE auth.users
    SET raw_user_meta_data = COALESCE(raw_user_meta_data, '{}'::jsonb) || '{"email_verified":true}'::jsonb
    WHERE NOT (COALESCE(raw_user_meta_data, '{}'::jsonb) ? 'email_verified') RETURNING id`);
  console.log(`metadata: email_verified set on ${(r2 || []).length || 0} rows`);
  const [left] = await sql.unsafe(
    `SELECT count(*)::int n FROM auth.users WHERE confirmation_token IS NULL OR recovery_token IS NULL OR instance_id IS NULL`);
  console.log(left.n === 0 ? "OK - no auth.users rows need repair" : `STILL ${left.n} rows need repair`);
}

function connect() {
  // --target routes to the migration target (Mumbai) instead of DATABASE_URL.
  const useTarget = process.argv.includes("--target");
  return postgres(useTarget ? targetDatabaseUrl() : databaseUrl(), {
    max: 1, connect_timeout: 20, idle_timeout: 5,
  });
}

async function listTables(sql) {
  const rows = await sql.unsafe(`
    SELECT table_name FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    ORDER BY table_name`);
  return rows.map((r) => r.table_name).filter((t) => !SKIP_TABLES.has("public." + t));
}

async function listColumns(sql, table) {
  const rows = await sql.unsafe(`
    SELECT a.attname AS col, format_type(a.atttypid, a.atttypmod) AS typ
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = $1
      AND a.attnum > 0 AND NOT a.attisdropped
    ORDER BY a.attnum`, [table]);
  return rows;
}

async function doExport() {
  const out = arg("out");
  if (!out) { console.error("export requires --out <file>"); process.exit(1); }
  const sql = connect();
  try {
    const [meta] = await sql.unsafe(`SELECT current_database() db, version() v,
      (SELECT inet_server_addr()::text) addr, now() at`);
    const tables = await listTables(sql);
    const data = {};
    for (const t of tables) {
      // The alias must never collide with a column name. `to_jsonb(x)` on
      // roadmap_nodes silently resolves to the integer column `x` instead of the
      // row, which exports every row as null. `__r` is reserved here.
      const clash = await sql.unsafe(
        `SELECT 1 FROM information_schema.columns
         WHERE table_schema='public' AND table_name=$1 AND column_name='__r'`, [t]);
      if (clash.length) throw new Error(`reserved alias __r collides with a column on ${t}`);
      const rows = await sql.unsafe(`SELECT to_jsonb(__r) AS j FROM public."${t}" AS __r`);
      data[t] = rows.map((r) => r.j);
      if (data[t].some((r) => r === null || typeof r !== "object")) {
        throw new Error(`export of ${t} produced a non-object row - check the to_jsonb alias`);
      }
    }
    let authUsers = [];
    let authIdentities = [];
    try {
      const u = await sql.unsafe(`SELECT to_jsonb(__u) AS j FROM auth.users AS __u`);
      authUsers = u.map((r) => r.j);
      const i = await sql.unsafe(`SELECT to_jsonb(__i) AS j FROM auth.identities AS __i`);
      authIdentities = i.map((r) => r.j);
    } catch (e) {
      console.warn("! auth export unavailable:", e.message);
    }

    const payload = {
      meta: {
        format: "loom-db-transfer/1",
        exported_at: new Date().toISOString(),
        source_db: meta.db,
        source_server: meta.addr,
        source_version: meta.v.split(",")[0],
        table_count: tables.length,
        row_total: Object.values(data).reduce((a, b) => a + b.length, 0),
        auth_user_count: authUsers.length,
        auth_identity_count: authIdentities.length,
      },
      tables: data,
      auth_users: authUsers,
      auth_identities: authIdentities,
    };
    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(payload, null, 0), "utf8");
    console.log(`exported -> ${out}`);
    console.log(`  ${payload.meta.row_total} rows across ${tables.length} tables`);
    console.log(`  auth.users=${authUsers.length} auth.identities=${authIdentities.length}`);
    console.log(`  ${(fs.statSync(out).size / 1024).toFixed(1)} KiB`);
  } finally { await sql.end(); }
}

async function doImport() {
  const inFile = arg("in");
  if (!inFile) { console.error("import requires --in <file>"); process.exit(1); }
  const payload = JSON.parse(fs.readFileSync(inFile, "utf8"));
  const dry = process.argv.includes("--dry-run");
  const sql = connect();
  let inserted = 0, skipped = 0, authU = 0, authI = 0;
  try {
    // Triggers off => no FK order requirements, no auth side-effect triggers.
    await sql.unsafe("SET session_replication_role = replica");
    try {
      if (process.argv.includes("--truncate")) {
        // Makes re-imports deterministic. Intended for a freshly migrated
        // target; never point this at a database holding live data.
        const tables = await listTables(sql);
        if (tables.length) {
          await sql.unsafe(
            `TRUNCATE TABLE ${tables.map((t) => `public."${t}"`).join(", ")} CASCADE`);
        }
        await sql.unsafe("TRUNCATE TABLE auth.identities, auth.users CASCADE");
        console.log(`truncated ${tables.length} public tables + auth users/identities`);
      }
      // GoTrue scopes users by auth.instances.id. On current Supabase projects
      // auth.instances is EMPTY and the default instance is the zero UUID, so
      // "no instance row" must become the zero UUID -- leaving instance_id NULL
      // makes every user invisible to the auth API (login and /admin/users both
      // return nothing) even though the rows are present in the table.
      const [inst] = await sql.unsafe("SELECT id FROM auth.instances LIMIT 1");
      const instanceId = inst ? inst.id : "00000000-0000-0000-0000-000000000000";
      if (!inst) console.log("  auth.instances is empty -> using the default zero-UUID instance id");

      for (const [table, rows] of Object.entries(payload.tables)) {
        if (!rows.length) { skipped++; continue; }
        if (dry) { inserted += rows.length; continue; }
        const cols = await listColumns(sql, table);
        if (!cols.length) { console.warn(`! target missing table ${table}`); skipped++; continue; }
        const names = cols.map((c) => c.col);
        const present = rows.some((r) => names.some((n) => n in r));
        if (!present) { console.warn(`! no overlapping columns for ${table}`); skipped++; continue; }
        const use = names.filter((n) => rows.some((r) => n in r));
        const colList = use.map((n) => `"${n}"`).join(", ");
        const recList = use.map((n) => `${n} ${cols.find((c) => c.col === n).typ}`).join(", ");
        const selList = use.map((n) => `r."${n}"`).join(", ");
        await sql.unsafe(
          `INSERT INTO public."${table}" (${colList})
           SELECT ${selList} FROM jsonb_to_recordset($1::text::jsonb) AS r(${recList})`,
          [JSON.stringify(rows.map((row) => { const o = {}; for (const n of use) o[n] = row[n]; return o; }))]
        );
        inserted += rows.length;
        console.log(`  ${table}: ${rows.length}`);
      }

      // Introspect the target so we only write columns that exist and are not
      // generated/identity. Supabase computes confirmed_at from the *_confirmed_at
      // columns, so writing it directly is rejected by Postgres.
      const authCols = await sql.unsafe(`
        SELECT a.attname AS col
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'auth' AND c.relname = $1
          AND a.attnum > 0 AND NOT a.attisdropped
          AND a.attgenerated = '' AND a.attidentity = ''`, ["users"]);
      const authColSet = new Set(authCols.map((c) => c.col));
      const userCols = AUTH_USER_COLS.filter((c) => authColSet.has(c));
      const skipCols = AUTH_USER_COLS.filter((c) => !authColSet.has(c));
      if (skipCols.length) console.log(`  auth.users: skipping non-writable -> ${skipCols.join(", ")}`);

      for (const u of payload.auth_users || []) {
        if (dry) { authU++; continue; }
        const pick = {};
        for (const c of userCols) if (c in u) pick[c] = u[c];
        for (const c of NULLABLE_AS_EMPTY) if (c in pick && pick[c] === null) pick[c] = "";
        if (instanceId) pick.instance_id = instanceId;
        const names = Object.keys(pick);
        await sql.unsafe(
          `INSERT INTO auth.users (${names.map((n) => `"${n}"`).join(",")})
           VALUES (${names.map((n) => `$${names.indexOf(n) + 1}`).join(",")})`,
          names.map((n) => pick[n])
        );
        authU++;
      }
      // auth.identities also gains computed columns over time (e.g. `email` is
      // generated from identity_data), so the writable set is introspected too.
      const idCols = await sql.unsafe(`
        SELECT a.attname AS col
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'auth' AND c.relname = $1
          AND a.attnum > 0 AND NOT a.attisdropped
          AND a.attgenerated = '' AND a.attidentity = ''`, ["identities"]);
      const idColSet = new Set(idCols.map((c) => c.col));
      const identityCols = AUTH_IDENTITY_COLS.filter((c) => idColSet.has(c));
      const skipIdCols = AUTH_IDENTITY_COLS.filter((c) => !idColSet.has(c));
      if (skipIdCols.length) console.log(`  auth.identities: skipping non-writable -> ${skipIdCols.join(", ")}`);

      for (const i of payload.auth_identities || []) {
        if (dry) { authI++; continue; }
        const pick = {};
        for (const c of identityCols) if (c in i) pick[c] = i[c];
        const names = Object.keys(pick);
        await sql.unsafe(
          `INSERT INTO auth.identities (${names.map((n) => `"${n}"`).join(",")})
           VALUES (${names.map((n) => `$${names.indexOf(n) + 1}`).join(",")})`,
          names.map((n) => pick[n])
        );
        authI++;
      }
    } finally {
      await sql.unsafe("SET session_replication_role = origin");
    }
    console.log(`import${dry ? " (DRY RUN)" : ""}: ${inserted} rows across ${Object.keys(payload.tables).length} tables (${skipped} empty/absent)`);
    console.log(`  auth.users=${authU} auth.identities=${authI}`);
  } finally { await sql.end(); }
}

async function doVerify() {
  const inFile = arg("in");
  if (!inFile) { console.error("verify requires --in <file>"); process.exit(1); }
  const payload = JSON.parse(fs.readFileSync(inFile, "utf8"));
  const sql = connect();
  let ok = 0, bad = 0, missing = 0;
  try {
    console.log("table".padEnd(34), "expected".padStart(9), "actual".padStart(8), "  status");
    for (const [table, rows] of Object.entries(payload.tables)) {
      const want = rows.length;
      let got = null;
      try {
        const [r] = await sql.unsafe(`SELECT count(*)::int AS n FROM public."${table}"`);
        got = r.n;
      } catch { got = null; }
      let status;
      if (got === null) { status = "MISSING"; missing++; }
      else if (got === want) { status = "ok"; ok++; }
      else if (got > want) { status = "ok(+seeded)"; ok++; }
      else { status = "SHORT"; bad++; }
      console.log(table.padEnd(34), String(want).padStart(9), String(got).padStart(8), "  " + status);
    }
    try {
      const [u] = await sql.unsafe("SELECT count(*)::int AS n FROM auth.users");
      console.log("auth.users".padEnd(34), String(payload.meta.auth_user_count).padStart(9), String(u.n).padStart(8),
        "  " + (u.n === payload.meta.auth_user_count ? "ok" : "SHORT"));
    } catch {}
    console.log(`\nmatched=${ok} short=${bad} missing=${missing}`);
    if (bad || missing) process.exitCode = 1;
  } finally { await sql.end(); }
}

async function doDiff() {
  const a = JSON.parse(fs.readFileSync(arg("a"), "utf8"));
  const b = JSON.parse(fs.readFileSync(arg("b"), "utf8"));
  const keys = new Set([...Object.keys(a.tables), ...Object.keys(b.tables)]);
  let diffs = 0;
  for (const t of [...keys].sort()) {
    const wa = a.tables[t]?.length ?? 0;
    const wb = b.tables[t]?.length ?? 0;
    if (wa !== wb) { console.log(`${t.padEnd(34)} A=${wa} B=${wb}`); diffs++; }
  }
  console.log(`\n${keys.size} tables compared, ${diffs} row-count differences.`);
}

const sql = connect();
try {
  if (mode === "export") await doExport();
  else if (mode === "import") await doImport();
  else if (mode === "verify") await doVerify();
  else if (mode === "diff") await doDiff();
  else if (mode === "repair-auth") await doRepairAuth();
  else {
    console.error("usage: db-transfer.js export|import|verify|diff|repair-auth [--target] [--out|--in|--a|--b] [file]");
    process.exitCode = 1;
  }
} catch (e) {
  console.error("db-transfer failed:", e.message);
  process.exitCode = 1;
} finally {
  await sql.end();
}