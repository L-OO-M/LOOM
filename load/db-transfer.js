// Logical export/import for a L.O.O.M. database.
//
// Used to move a development database between Supabase projects (e.g. when a
// project must be recreated in another region). Schema is NOT transferred here
// -- that is load/migrations/000_base_schema.sql + 001..N. Only rows move.
//
//   export  node --import ./load/env-local.js load/db-transfer.js export --out load/snapshots/x.json
//   import  node --import ./load/env-local.js load/db-transfer.js import --in  load/snapshots/x.json
//   verify  node --import ./load/env-local.js load/db-transfer.js verify --in  load/snapshots/x.json
//   diff    node --import ./load/env-local.js load/db-transfer.js diff   --a a.json --b b.json
//
// Row fidelity: every row is exported as `to_jsonb(row)`, so Postgres itself
// performs the type->JSON conversion (timestamptz, numeric, uuid, jsonb, text[],
// bytea all round-trip through their canonical input form). Import casts each
// JSON key back to the live column type via jsonb_to_recordset, so there is no
// per-value guessing.
//
// auth.users / auth.identities are copied too, preserving UUIDs and bcrypt
// `encrypted_password` hashes so existing logins survive the move.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postgres from "postgres";
import { databaseUrl } from "./env-local.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Never move the migration ledger — the target tracks its own applied state.
const SKIP_TABLES = new Set(["public.schema_migrations"]);

// auth.users columns that are safe and meaningful to carry across projects.
// Everything else (flow state, one-time tokens, sessions, SSO) is per-project
// runtime state and must be regenerated by the target.
const AUTH_USER_COLS = [
  "id", "aud", "role", "email", "encrypted_password", "email_confirmed_at",
  "invited_at", "confirmation_token", "confirmation_sent_at",
  "email_change_token_new", "email_change", "email_change_sent_at",
  "last_sign_in_at", "raw_app_meta_data", "raw_user_meta_data",
  "is_super_admin", "created_at", "updated_at",
  "phone", "phone_confirmed_at", "confirmed_at", "recovery_token", "recovery_sent_at",
];
const AUTH_IDENTITY_COLS = [
  "id", "user_id", "identity_data", "provider", "created_at", "updated_at",
];

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
};
const mode = process.argv[2];

function connect() {
  return postgres(databaseUrl(), { max: 1, connect_timeout: 20, idle_timeout: 5 });
}

async function listTables(sql) {
  const rows = await sql.unsafe(`
    SELECT table_name FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    ORDER BY table_name`);
  return rows.map((r) => r.table_name).filter((t) => !SKIP_TABLES.has("public." + t));
}

async function listColumns(sql, table) {
  const rows = await sql.unsafe(`
    SELECT a.attname AS col, format_type(a.atttypid, a.atttypmod) AS typ
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = $1
      AND a.attnum > 0 AND NOT a.attisdropped
    ORDER BY a.attnum`, [table]);
  return rows;
}

async function doExport() {
  const out = arg("out");
  if (!out) { console.error("export requires --out <file>"); process.exit(1); }
  const sql = connect();
  try {
    const [meta] = await sql.unsafe(`SELECT current_database() db, version() v,
      (SELECT inet_server_addr()::text) addr, now() at`);
    const tables = await listTables(sql);
    const data = {};
    for (const t of tables) {
      const rows = await sql.unsafe(`SELECT to_jsonb(x) AS j FROM public."${t}" x`);
      data[t] = rows.map((r) => r.j);
    }
    let authUsers = [];
    let authIdentities = [];
    try {
      const u = await sql.unsafe(`SELECT to_jsonb(x) AS j FROM auth.users x`);
      authUsers = u.map((r) => r.j);
      const i = await sql.unsafe(`SELECT to_jsonb(x) AS j FROM auth.identities x`);
      authIdentities = i.map((r) => r.j);
    } catch (e) {
      console.warn("! auth export unavailable:", e.message);
    }

    const payload = {
      meta: {
        format: "loom-db-transfer/1",
        exported_at: new Date().toISOString(),
        source_db: meta.db,
        source_server: meta.addr,
        source_version: meta.v.split(",")[0],
        table_count: tables.length,
        row_total: Object.values(data).reduce((a, b) => a + b.length, 0),
        auth_user_count: authUsers.length,
        auth_identity_count: authIdentities.length,
      },
      tables: data,
      auth_users: authUsers,
      auth_identities: authIdentities,
    };
    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(payload, null, 0), "utf8");
    console.log(`exported -> ${out}`);
    console.log(`  ${payload.meta.row_total} rows across ${tables.length} tables`);
    console.log(`  auth.users=${authUsers.length} auth.identities=${authIdentities.length}`);
    console.log(`  ${(fs.statSync(out).size / 1024).toFixed(1)} KiB`);
  } finally { await sql.end(); }
}

async function doImport() {
  const inFile = arg("in");
  if (!inFile) { console.error("import requires --in <file>"); process.exit(1); }
  const payload = JSON.parse(fs.readFileSync(inFile, "utf8"));
  const dry = process.argv.includes("--dry-run");
  const sql = connect();
  let inserted = 0, skipped = 0, authU = 0, authI = 0;
  try {
    // Triggers off => no FK order requirements, no auth side-effect triggers.
    await sql.unsafe("SET session_replication_role = replica");
    try {
      const [inst] = await sql.unsafe("SELECT id FROM auth.instances LIMIT 1");
      const instanceId = inst ? inst.id : null;

      for (const [table, rows] of Object.entries(payload.tables)) {
        if (!rows.length) { skipped++; continue; }
        if (dry) { inserted += rows.length; continue; }
        const cols = await listColumns(sql, table);
        if (!cols.length) { console.warn(`! target missing table ${table}`); skipped++; continue; }
        const names = cols.map((c) => c.col);
        const present = rows.some((r) => names.some((n) => n in r));
        if (!present) { console.warn(`! no overlapping columns for ${table}`); skipped++; continue; }
        const use = names.filter((n) => rows.some((r) => n in r));
        const colList = use.map((n) => `"${n}"`).join(", ");
        const recList = use.map((n) => `${n} ${cols.find((c) => c.col === n).typ}`).join(", ");
        const selList = use.map((n) => `r."${n}"`).join(", ");
        await sql.unsafe(
          `INSERT INTO public."${table}" (${colList})
           SELECT ${selList} FROM jsonb_to_recordset($1::jsonb) AS r(${recList})`,
          [JSON.stringify(rows.map((row) => { const o = {}; for (const n of use) o[n] = row[n]; return o; }))]
        );
        inserted += rows.length;
        console.log(`  ${table}: ${rows.length}`);
      }

      for (const u of payload.auth_users || []) {
        if (dry) { authU++; continue; }
        const pick = {};
        for (const c of AUTH_USER_COLS) if (c in u) pick[c] = u[c];
        if (instanceId) pick.instance_id = instanceId;
        const names = Object.keys(pick);
        await sql.unsafe(
          `INSERT INTO auth.users (${names.map((n) => `"${n}"`).join(",")})
           VALUES (${names.map((n) => `$${names.indexOf(n) + 1}`).join(",")})`,
          names.map((n) => pick[n])
        );
        authU++;
      }
      for (const i of payload.auth_identities || []) {
        if (dry) { authI++; continue; }
        const pick = {};
        for (const c of AUTH_IDENTITY_COLS) if (c in i) pick[c] = i[c];
        const names = Object.keys(pick);
        await sql.unsafe(
          `INSERT INTO auth.identities (${names.map((n) => `"${n}"`).join(",")})
           VALUES (${names.map((n) => `$${names.indexOf(n) + 1}`).join(",")})`,
          names.map((n) => pick[n])
        );
        authI++;
      }
    } finally {
      await sql.unsafe("SET session_replication_role = origin");
    }
    console.log(`import${dry ? " (DRY RUN)" : ""}: ${inserted} rows across ${Object.keys(payload.tables).length} tables (${skipped} empty/absent)`);
    console.log(`  auth.users=${authU} auth.identities=${authI}`);
  } finally { await sql.end(); }
}

async function doVerify() {
  const inFile = arg("in");
  if (!inFile) { console.error("verify requires --in <file>"); process.exit(1); }
  const payload = JSON.parse(fs.readFileSync(inFile, "utf8"));
  const sql = connect();
  let ok = 0, bad = 0, missing = 0;
  try {
    console.log("table".padEnd(34), "expected".padStart(9), "actual".padStart(8), "  status");
    for (const [table, rows] of Object.entries(payload.tables)) {
      const want = rows.length;
      let got = null;
      try {
        const [r] = await sql.unsafe(`SELECT count(*)::int AS n FROM public."${table}"`);
        got = r.n;
      } catch { got = null; }
      let status;
      if (got === null) { status = "MISSING"; missing++; }
      else if (got === want) { status = "ok"; ok++; }
      else if (got > want) { status = "ok(+seeded)"; ok++; }
      else { status = "SHORT"; bad++; }
      console.log(table.padEnd(34), String(want).padStart(9), String(got).padStart(8), "  " + status);
    }
    try {
      const [u] = await sql.unsafe("SELECT count(*)::int AS n FROM auth.users");
      console.log("auth.users".padEnd(34), String(payload.meta.auth_user_count).padStart(9), String(u.n).padStart(8),
        "  " + (u.n === payload.meta.auth_user_count ? "ok" : "SHORT"));
    } catch {}
    console.log(`\nmatched=${ok} short=${bad} missing=${missing}`);
    if (bad || missing) process.exitCode = 1;
  } finally { await sql.end(); }
}

async function doDiff() {
  const a = JSON.parse(fs.readFileSync(arg("a"), "utf8"));
  const b = JSON.parse(fs.readFileSync(arg("b"), "utf8"));
  const keys = new Set([...Object.keys(a.tables), ...Object.keys(b.tables)]);
  let diffs = 0;
  for (const t of [...keys].sort()) {
    const wa = a.tables[t]?.length ?? 0;
    const wb = b.tables[t]?.length ?? 0;
    if (wa !== wb) { console.log(`${t.padEnd(34)} A=${wa} B=${wb}`); diffs++; }
  }
  console.log(`\n${keys.size} tables compared, ${diffs} row-count differences.`);
}

const sql = connect();
try {
  if (mode === "export") await doExport();
  else if (mode === "import") await doImport();
  else if (mode === "verify") await doVerify();
  else if (mode === "diff") await doDiff();
  else {
    console.error("usage: db-transfer.js export|import|verify|diff [--out|--in|--a|--b] [file]");
    process.exitCode = 1;
  }
} catch (e) {
  console.error("db-transfer failed:", e.message);
  process.exitCode = 1;
} finally {
  await sql.end();
}